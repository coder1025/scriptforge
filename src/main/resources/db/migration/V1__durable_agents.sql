CREATE TABLE tasks (
  id VARCHAR(36) PRIMARY KEY, request_id VARCHAR(100) NOT NULL UNIQUE,
  request_hash VARCHAR(64) NOT NULL, title VARCHAR(160) NOT NULL,
  status VARCHAR(32) NOT NULL, mode VARCHAR(16) NOT NULL, input_json CLOB NOT NULL,
  plan_revision INT NOT NULL DEFAULT 0, draft_revision INT NOT NULL DEFAULT 0,
  review_round INT NOT NULL DEFAULT 0, model_calls INT NOT NULL DEFAULT 0,
  max_model_calls INT NOT NULL, used_tokens BIGINT NOT NULL DEFAULT 0,
  reserved_tokens BIGINT NOT NULL DEFAULT 0, max_tokens BIGINT NOT NULL,
  error VARCHAR(2000), created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE executions (
  id VARCHAR(36) PRIMARY KEY, task_id VARCHAR(36) NOT NULL REFERENCES tasks(id),
  role VARCHAR(16) NOT NULL, status VARCHAR(32) NOT NULL,
  plan_revision INT NOT NULL, draft_revision INT NOT NULL,
  parent_step_id BIGINT UNIQUE, coverage_json CLOB NOT NULL,
  lease_owner VARCHAR(80), lease_epoch BIGINT NOT NULL DEFAULT 0,
  lease_until TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_execution_work ON executions(status, lease_until, created_at);
CREATE TABLE steps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id VARCHAR(36) NOT NULL REFERENCES tasks(id), execution_id VARCHAR(36) NOT NULL REFERENCES executions(id),
  kind VARCHAR(16) NOT NULL, name VARCHAR(80) NOT NULL, status VARCHAR(24) NOT NULL,
  parent_model_id BIGINT REFERENCES steps(id), provider_call_id VARCHAR(200),
  input_json CLOB NOT NULL, output_json CLOB, reserved_tokens BIGINT NOT NULL DEFAULT 0,
  input_tokens BIGINT, output_tokens BIGINT, usage_status VARCHAR(16) NOT NULL DEFAULT 'NONE',
  estimated_tokens INT NOT NULL DEFAULT 0, lease_epoch BIGINT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE(execution_id, provider_call_id)
);
CREATE INDEX idx_steps_task ON steps(task_id,id);
CREATE TABLE artifacts (
  id VARCHAR(36) PRIMARY KEY, task_id VARCHAR(36) NOT NULL REFERENCES tasks(id),
  kind VARCHAR(16) NOT NULL, revision INT NOT NULL, plan_revision INT NOT NULL,
  hash VARCHAR(64) NOT NULL, value_json CLOB NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE(task_id,kind,revision)
);
CREATE TABLE reports (
  id VARCHAR(36) PRIMARY KEY, task_id VARCHAR(36) NOT NULL REFERENCES tasks(id),
  execution_id VARCHAR(36) NOT NULL UNIQUE REFERENCES executions(id),
  plan_revision INT NOT NULL, draft_revision INT NOT NULL, draft_hash VARCHAR(64) NOT NULL,
  value_json CLOB NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE checkpoints (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id VARCHAR(36) NOT NULL REFERENCES tasks(id), execution_id VARCHAR(36) NOT NULL REFERENCES executions(id),
  plan_revision INT NOT NULL, draft_revision INT NOT NULL, estimated_tokens INT NOT NULL,
  compacted BOOLEAN NOT NULL, state_json CLOB NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE commands (
  task_id VARCHAR(36) NOT NULL REFERENCES tasks(id), request_id VARCHAR(100) NOT NULL,
  command_type VARCHAR(16) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  PRIMARY KEY(task_id,request_id)
);
CREATE TABLE templates (
  id VARCHAR(36) PRIMARY KEY, name VARCHAR(100) NOT NULL, version INT NOT NULL,
  instructions CLOB NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE(name,version)
);
